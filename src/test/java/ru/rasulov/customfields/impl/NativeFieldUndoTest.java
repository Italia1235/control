    @Test public void secondFieldCreateFailingAfterStoringBlocksRollbackKeepsTheFirstFieldAndSeparatesWhatIsConfirmed() throws Exception {
        try (Model model = new Model()) {
            try { model.createTwo(); fail("the failed native create must escape the service"); }
            catch (IllegalStateException expected) { }
            Map<String, Object> operation = model.fixture.reopen().getOperation(model.operation(), "admin");
            assertEquals("an unproven create must not be rolled back or reported as nothing changed", "BLOCKED", operation.get("status"));
            assertTrue("the first field was created and stays", model.exists.get());
            assertEquals(0, model.deletions.get());
            assertNull("the escaped failure leaves no domain result", operation.get("result"));
            assertTrue(String.valueOf(operation.get("error")).contains("Field B"));
            List<Map<String, Object>> steps = (List<Map<String, Object>>) operation.get("steps");
            for (Map<String, Object> step : steps) {
                boolean second = String.valueOf(step.get("resource")).endsWith("Field B");
                assertEquals(String.valueOf(step), second ? false : true, "APPLIED".equals(step.get("status")));
            }
            assertTrue("the second field's step exists but is not proven", steps.stream()
                    .anyMatch(s -> String.valueOf(s.get("resource")).endsWith("Field B")));
            for (Map<String, Object> step : steps) {
                boolean second = String.valueOf(step.get("resource")).endsWith("Field B");
                assertEquals("only the confirmed create names its field id; the unproven one stays unidentified: " + step,
                        second ? null : Model.FIELD, step.get("fieldId"));
            }
            assertTrue("the name-only resource stays the undo identity", steps.stream()
                    .allMatch(s -> String.valueOf(s.get("resource")).startsWith("cf.field:")));
            assertEquals("the second field exists in Jira although no step proves it", true, model.secondCreated.get());
        }
    }

